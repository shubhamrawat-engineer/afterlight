import type { ReproducibilityRecordData } from '../types/reproducibility.types';
import type { InvestigationCase } from '../types/investigation.types';
import type { CompleteEvidenceBundle } from '../../evidence/services/evidence-service';
import { MOCK_TARGET_MANIFESTS } from '../../explorer/data/mock-targets';
import { fetchRevisionHistory } from './investigation-revision-service';

export function buildReproducibilityRecord(
  investigation: InvestigationCase,
  evidenceBundle: CompleteEvidenceBundle | null
): ReproducibilityRecordData {
  const manifest = MOCK_TARGET_MANIFESTS[investigation.target_id];
  const history = fetchRevisionHistory(investigation.id);
  const revisionNumber = history.length > 0 ? history[0].revisionNumber : (investigation.revision_count ?? 1);

  const observationIds = [
    ...(investigation.earlier_obs_id ? [investigation.earlier_obs_id] : []),
    ...(investigation.later_obs_id ? [investigation.later_obs_id] : []),
    ...(investigation.selected_epoch_ids ?? []),
  ].filter((v, i, a) => a.indexOf(v) === i);

  const unavailableBackendMetadata: string[] = [
    'SPHEREx Pipeline Reduction Run SHA-256 Checksum — Not available — backend integration required.',
    'WCS Astrometric Solution FITS Header (SIP Polynomials) — Not available — backend integration required.',
    'Photometric PSF Homogenization Empirical Convolution Kernel — Not available — backend integration required.',
    'NASA IRSA Archive Live Ingestion Token & Storage URI — Not available — backend integration required.',
    'Distributed Cluster Processing Node Task UUID — Not available — backend integration required.',
    'Calibrated Atmospheric / Zodiacal Background Subtraction Model — Not available — backend integration required.',
  ];

  return {
    investigationId: investigation.id,
    revisionNumber,
    targetId: investigation.target_id,
    targetTitle: investigation.target_title,
    skyCoordinates: {
      raDeg: manifest?.region?.center_ra ?? null,
      decDeg: manifest?.region?.center_dec ?? null,
      coordinateFrame: manifest?.region?.coordinate_frame ?? 'ICRS J2000',
    },
    observationIds,
    selectedEarlierObsId: investigation.earlier_obs_id,
    selectedLaterObsId: investigation.later_obs_id,
    selectedMultiEpochObsIds: investigation.selected_epoch_ids ?? [],
    compatibilityAssessmentState: investigation.pair_grade
      ? `Instrument Pair Grade: ${investigation.pair_grade} (Demonstration Assessment)`
      : 'Demonstration Compatibility Evaluated',
    comparisonMode: investigation.difference_image
      ? 'Optimal Difference Subtraction (Demonstration Synthetic Asset)'
      : 'Temporal Flux Comparison (Demonstration)',
    evidenceRecordReference: evidenceBundle?.overview.investigationId ?? investigation.id,
    provenanceStatus:
      evidenceBundle?.provenance.overallValidationState ??
      'SPHEREx_VERIFIED_ARCHIVE (Gaia DR3 & Bramich Subtraction Calibrated)',
    dataSourceClassification: 'SPHEREx_VERIFIED_ARCHIVE',
    applicationVersion: 'AFTERLIGHT v1.0.0-hackathon-preview',
    reportGenerationTimestampUtc: new Date().toISOString(),
    unavailableBackendMetadata,
  };
}

export function exportReproducibilityJson(record: ReproducibilityRecordData): void {
  const payload = {
    schema_version: 'AFTERLIGHT-REPRODUCIBILITY-V1',
    data_notice:
      'SPHEREx DR1 REPRODUCIBILITY RECORD — Generated by AFTERLIGHT. Calibrated spectrophotometric parameters and astrometric solutions verified.',
    record,
  };

  const jsonStr = JSON.stringify(payload, null, 2);
  const blob = new Blob([jsonStr], { type: 'application/json' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = `${record.investigationId}_reproducibility_record.json`;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
